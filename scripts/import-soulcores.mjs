#!/usr/bin/env node
/**
 * Soul core catalog (D-41) from TibiaWiki (CC BY-SA): every page in Category:Soul Cores gives the creature and
 * the item id (sprite on CipSoft's image server); the creature page gives the bestiary class and difficulty.
 *
 * Usage: node scripts/import-soulcores.mjs [--dry-run]     (needs internet, ~30 s)
 * Output: shared/soulcores.json  { _comment, generated, soulcores: [{ creature, itemId, bestiaryClass, difficulty }] }
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const API = 'https://tibia.fandom.com/api.php';
const UA = 'BagParser-catalog-import/1.0 (https://github.com/calefin/bagparser)';
const DRY_RUN = process.argv.includes('--dry-run');
const SUFFIX = ' Soul Core';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function api(params) {
  const url = `${API}?${new URLSearchParams({ format: 'json', formatversion: '2', ...params })}`;
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      await sleep(300); // be polite to the wiki
      return json;
    } catch (err) {
      if (attempt >= 4) throw err;
      await sleep(2000 * attempt);
    }
  }
}

async function categoryTitles(category) {
  const titles = [];
  let cont = {};
  do {
    const d = await api({ action: 'query', list: 'categorymembers', cmtitle: `Category:${category}`, cmnamespace: '0', cmlimit: '500', ...cont });
    titles.push(...d.query.categorymembers.map((m) => m.title));
    cont = d.continue ?? null;
  } while (cont);
  return titles;
}

/** Wikitext of many pages, 50 per request; follows redirects. Map title → wikitext */
async function wikitexts(titles) {
  const out = new Map();
  for (let i = 0; i < titles.length; i += 50) {
    const batch = titles.slice(i, i + 50);
    const d = await api({ action: 'query', prop: 'revisions', rvprop: 'content', rvslots: 'main', redirects: '1', titles: batch.join('|') });
    const back = new Map((d.query.redirects ?? []).map((r) => [r.to, r.from]));
    const norm = new Map((d.query.normalized ?? []).map((n) => [n.to, n.from]));
    for (const p of d.query.pages ?? []) {
      const text = p.revisions?.[0]?.slots?.main?.content;
      if (!text) continue;
      let title = p.title;
      title = back.get(title) ?? title;
      title = norm.get(title) ?? title;
      out.set(title, text);
    }
    process.stdout.write('.');
  }
  return out;
}

/** "| key = value" from an infobox */
export function field(wikitext, key) {
  // [ \t]* (not \s*) after "=": an empty field must not swallow the next line
  const m = new RegExp(`^[ \\t]*\\|[ \\t]*${key}[ \\t]*=[ \\t]*(.*)$`, 'mi').exec(wikitext);
  const v = m?.[1].trim();
  return v ? v : null;
}

const cap = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1).toLowerCase() : null);

async function main() {
  const coreTitles = (await categoryTitles('Soul Cores')).filter((t) => t.endsWith(SUFFIX));
  console.log(`${coreTitles.length} soul cores`);
  const coreText = await wikitexts(coreTitles);
  const creatures = coreTitles.map((t) => t.slice(0, -SUFFIX.length));
  const creatureText = await wikitexts(creatures);
  console.log('');

  const soulcores = [];
  const missing = [];
  for (const title of coreTitles) {
    const creature = title.slice(0, -SUFFIX.length);
    const core = coreText.get(title) ?? '';
    const page = creatureText.get(creature) ?? '';
    const itemId = Number(field(core, 'itemid')?.split(/[,\s]/)[0]) || 0;
    // No creature page = special core (e.g. "Ominous Soul Core", from a Soul Prism): not a bestiary creature
    if (!page) {
      missing.push(creature);
      continue;
    }
    soulcores.push({
      creature,
      itemId,
      bestiaryClass: field(page, 'bestiaryclass'),
      difficulty: cap(field(page, 'bestiarylevel')),
    });
  }
  soulcores.sort((a, b) => a.creature.localeCompare(b.creature));
  if (missing.length) console.warn(`Skipped (no creature page): ${missing.join(', ')}`);
  console.log(`classes: ${new Set(soulcores.map((s) => s.bestiaryClass)).size}, without item id: ${soulcores.filter((s) => !s.itemId).length}`);

  const out = {
    _comment: `Generated by scripts/import-soulcores.mjs on ${new Date().toISOString().slice(0, 10)} from TibiaWiki (CC BY-SA). Do not edit by hand.`,
    soulcores,
  };
  if (DRY_RUN) {
    console.log(JSON.stringify(soulcores.slice(0, 5), null, 1));
    return;
  }
  await writeFile(path.join(ROOT, 'shared/soulcores.json'), JSON.stringify(out, null, 1) + '\n');
  console.log('wrote shared/soulcores.json');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
