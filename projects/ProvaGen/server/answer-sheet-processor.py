#!/usr/bin/env python3
"""
Answer Sheet Processor — Prof-Aid
Reads scanned gabaritos generated by answerSheetSvg.ts.

Detection pipeline:
1. Locate the 4 ArUco-like corner markers (filled squares with inner pattern).
2. Compute perspective transform to deskew the sheet.
3. Decode the Code 128 barcode to extract the exam/form ID.
4. Locate bubble positions based on the expected grid layout.
5. Classify each bubble as filled or empty.
"""

import json
import sys
import base64
import math
from io import BytesIO
from pathlib import Path

import cv2
import numpy as np

# ── Try to import barcode decoder (optional) ───────────────────────────────
try:
    from pyzbar.pyzbar import decode as pyzbar_decode
    HAS_PYZBAR = True
except ImportError:
    HAS_PYZBAR = False


# ── Constants matching answerSheetSvg.ts geometry (at 72 dpi, A4) ─────────
PAGE_W = 595
PAGE_H = 842
MARGIN = 20
ARUCO  = 24   # marker outer size in SVG points


class AnswerSheetProcessor:
    def __init__(self, image_data: str, num_questions: int = 50, num_alternatives: int = 5):
        self.num_questions   = num_questions
        self.num_alternatives = num_alternatives
        self.image           = self._load(image_data)
        self.warped          = None   # perspective-corrected image
        self.answers: list   = []
        self.confidence: list = []
        self.form_id: str | None = None

    # ── Image loading ──────────────────────────────────────────────────────

    def _load(self, data: str) -> np.ndarray:
        if isinstance(data, str) and Path(data).exists():
            img = cv2.imread(data)
            if img is None:
                raise ValueError(f"Cannot read: {data}")
            return img
        try:
            raw = base64.b64decode(data)
            arr = np.frombuffer(raw, np.uint8)
            img = cv2.imdecode(arr, cv2.IMREAD_COLOR)
            if img is None:
                raise ValueError("Failed to decode base64 image")
            return img
        except Exception as e:
            raise ValueError(f"Image load failed: {e}")

    # ── Corner detection ───────────────────────────────────────────────────

    def _find_corners(self, gray: np.ndarray) -> list[tuple[int, int]] | None:
        """
        Find the 4 ArUco-like corner markers.
        Strategy: find the 4 largest roughly-square dark blobs near the page corners.
        Returns [TL, TR, BL, BR] as (x, y) of the top-left pixel of each marker,
        or None if detection fails.
        """
        _, binary = cv2.threshold(gray, 100, 255, cv2.THRESH_BINARY_INV)
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (3, 3))
        binary = cv2.morphologyEx(binary, cv2.MORPH_CLOSE, kernel)

        contours, _ = cv2.findContours(binary, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        h, w = gray.shape
        # Partition image into 4 quadrants; find the best candidate in each
        quadrant_corners = []
        quadrant_regions = [
            (0, 0, w // 2, h // 2),            # TL quadrant
            (w // 2, 0, w, h // 2),             # TR quadrant
            (0, h // 2, w // 2, h),             # BL quadrant
            (w // 2, h // 2, w, h),             # BR quadrant
        ]

        for (rx1, ry1, rx2, ry2) in quadrant_regions:
            best = None
            best_score = 0
            for cnt in contours:
                area = cv2.contourArea(cnt)
                if area < 50:
                    continue
                x, y, bw, bh = cv2.boundingRect(cnt)
                cx, cy = x + bw // 2, y + bh // 2
                if not (rx1 <= cx < rx2 and ry1 <= cy < ry2):
                    continue
                # Prefer square-ish blobs
                aspect = min(bw, bh) / max(bw, bh) if max(bw, bh) > 0 else 0
                if aspect < 0.5:
                    continue
                score = area * aspect
                if score > best_score:
                    best_score = score
                    best = (x, y, bw, bh)
            if best is None:
                return None
            quadrant_corners.append(best)

        # Convert to corner points (outer corners of each marker box)
        (tl_x, tl_y, tl_w, tl_h) = quadrant_corners[0]
        (tr_x, tr_y, tr_w, tr_h) = quadrant_corners[1]
        (bl_x, bl_y, bl_w, bl_h) = quadrant_corners[2]
        (br_x, br_y, br_w, br_h) = quadrant_corners[3]

        return [
            (tl_x, tl_y),
            (tr_x + tr_w, tr_y),
            (bl_x, bl_y + bl_h),
            (br_x + br_w, br_y + br_h),
        ]

    # ── Perspective correction ─────────────────────────────────────────────

    def _warp(self, corners: list[tuple[int, int]]) -> np.ndarray:
        """Warp image so the 4 corners map to the page rectangle."""
        src = np.float32(corners)
        w = max(
            math.dist(corners[0], corners[1]),
            math.dist(corners[2], corners[3]),
        )
        h = max(
            math.dist(corners[0], corners[2]),
            math.dist(corners[1], corners[3]),
        )
        dst = np.float32([[0, 0], [w, 0], [0, h], [w, h]])
        M   = cv2.getPerspectiveTransform(src, dst)
        return cv2.warpPerspective(self.image, M, (int(w), int(h)))

    # ── Barcode decoding ───────────────────────────────────────────────────

    def _decode_barcode(self, warped: np.ndarray) -> str | None:
        if not HAS_PYZBAR:
            return None
        # Crop bottom strip where the barcode lives
        h, w = warped.shape[:2]
        strip = warped[int(h * 0.88):h, int(w * 0.04):int(w * 0.75)]
        results = pyzbar_decode(strip)
        for r in results:
            return r.data.decode("utf-8", errors="replace")
        return None

    # ── Bubble detection ───────────────────────────────────────────────────

    def _detect_bubbles(self, gray: np.ndarray) -> tuple[list, list]:
        """
        Locate filled bubbles in the warped grayscale image.
        Uses adaptive threshold + contour detection.
        """
        blur   = cv2.GaussianBlur(gray, (5, 5), 0)
        thresh = cv2.adaptiveThreshold(
            blur, 255,
            cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
            cv2.THRESH_BINARY_INV,
            11, 4,
        )

        contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        h, w = gray.shape
        bubbles: list[tuple[int, int, int, int]] = []

        for cnt in contours:
            area = cv2.contourArea(cnt)
            if area < 30 or area > 800:
                continue
            x, y, bw, bh = cv2.boundingRect(cnt)
            aspect = min(bw, bh) / max(bw, bh) if max(bw, bh) > 0 else 0
            if aspect < 0.55:
                continue
            # Exclude corner/barcode areas (top 15% and bottom 12%)
            if y < h * 0.15 or y + bh > h * 0.88:
                continue
            bubbles.append((x, y, bw, bh))

        # Sort top-to-bottom, then left-to-right
        bubbles.sort(key=lambda b: (b[1] // 10, b[0]))

        answers: list[str | None] = []
        confidence: list[float]   = []

        # Group into questions (num_alternatives bubbles per question)
        for q in range(self.num_questions):
            start = q * self.num_alternatives
            end   = start + self.num_alternatives
            if end > len(bubbles):
                break

            group = bubbles[start:end]
            max_fill = 0.0
            max_idx  = -1

            for alt_idx, (bx, by, bw, bh) in enumerate(group):
                roi = self.image[by:by + bh, bx:bx + bw]
                roi_gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
                _, roi_bin = cv2.threshold(roi_gray, 180, 255, cv2.THRESH_BINARY_INV)
                fill = (np.count_nonzero(roi_bin) / roi_bin.size) * 100
                if fill > max_fill:
                    max_fill = fill
                    max_idx  = alt_idx

            if max_fill > 12:
                answers.append(chr(65 + max_idx))
                confidence.append(min(max_fill / 50.0, 1.0))
            else:
                answers.append(None)
                confidence.append(0.0)

        return answers, confidence

    # ── Main entry ─────────────────────────────────────────────────────────

    def process(self) -> dict:
        try:
            gray = cv2.cvtColor(self.image, cv2.COLOR_BGR2GRAY)

            # 1. Locate corners
            corners = self._find_corners(gray)

            # 2. Perspective correction (best-effort; skip if corners not found)
            if corners:
                self.warped = self._warp(corners)
                proc_img    = self.warped
                proc_gray   = cv2.cvtColor(proc_img, cv2.COLOR_BGR2GRAY)
            else:
                proc_img  = self.image
                proc_gray = gray

            # 3. Decode barcode
            self.form_id = self._decode_barcode(proc_img)

            # 4. Detect answers
            self.answers, self.confidence = self._detect_bubbles(proc_gray)

            return {
                "success":            True,
                "answers":            self.answers,
                "confidenceScores":   self.confidence,
                "numQuestionsDetected": len(self.answers),
                "cornersFound":       corners is not None,
                "formId":             self.form_id,
            }

        except Exception as e:
            return {"success": False, "error": str(e)}

    def compare_with_answer_key(self, answer_key: list) -> dict:
        if not self.answers:
            return {"error": "No answers extracted yet"}

        correct = incorrect = unanswered = 0
        results = []
        for i, (extracted, correct_ans) in enumerate(zip(self.answers, answer_key)):
            if extracted is None:
                status = "unanswered"; unanswered += 1
            elif extracted == correct_ans:
                status = "correct";   correct += 1
            else:
                status = "incorrect"; incorrect += 1
            results.append({
                "question":   i + 1,
                "extracted":  extracted,
                "correct":    correct_ans,
                "status":     status,
                "confidence": self.confidence[i] if i < len(self.confidence) else 0,
            })

        score = (correct / len(answer_key) * 100) if answer_key else 0
        return {
            "success":        True,
            "score":          score,
            "correctCount":   correct,
            "incorrectCount": incorrect,
            "unansweredCount": unanswered,
            "results":        results,
        }


def main():
    if len(sys.argv) < 2:
        print(json.dumps({"error": "Missing input JSON"}))
        sys.exit(1)
    try:
        inp           = json.loads(sys.argv[1])
        image_data    = inp.get("imageData")
        num_questions = inp.get("numQuestions", 50)
        num_alts      = inp.get("numAlternatives", 5)
        answer_key    = inp.get("answerKey")

        if not image_data:
            print(json.dumps({"error": "Missing imageData"}))
            sys.exit(1)

        proc   = AnswerSheetProcessor(image_data, num_questions, num_alts)
        result = proc.process()

        if result.get("success") and answer_key:
            result["comparison"] = proc.compare_with_answer_key(answer_key)

        print(json.dumps(result))

    except Exception as e:
        print(json.dumps({"error": str(e)}))
        sys.exit(1)


if __name__ == "__main__":
    main()
