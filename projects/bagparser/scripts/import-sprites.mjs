#!/usr/bin/env node
/**
 * Builds the item image index (D-35). Primary source: CipSoft's own image server
 * (static.tibia.com/images/charactertrade/objects/<item id>.gif, as used by the Char Bazaar), by the
 * client item id taken from TibiaWiki. Fallback: the image path on TibiaWiki's CDN.
 * Images are CipSoft artwork shown under the Tibia Fansite Agreement with credit on the site.
 * No image files are copied: the visitor's browser loads them (cached by our service worker).
 *
 *   node scripts/import-sprites.mjs
 *
 * Input:  shared/item-wiki.json (item name → wiki page title; written by import-tibiawiki.mjs)
 * Output: frontend/public/sprites/items.json  { official, wiki, sprites: { <slug>: [itemId|0, "<wiki path>"] } }
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const API = 'https://tibia.fandom.com/api.php';
const UA = 'BagParser sprite importer (+https://bagparser.com)';
const OUT = path.join(ROOT, 'frontend/public/sprites');
const CDN = 'https://static.wikia.nocookie.net/tibia/images/';

/** Coins come from shared/items.overrides.json, so they are not in item-wiki.json */
const COINS = { 'gold-coin': 'b/b0/Gold_Coin.gif', 'platinum-coin': 'f/f8/Platinum_Coin.gif', 'crystal-coin': '5/55/Crystal_Coin.gif' };

/** Same slug rule the frontend uses (frontend/src/core/sprites.ts) */
export const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function api(params) {
  const url = `${API}?${new URLSearchParams({ format: 'json', formatversion: '2', ...params })}`;
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA } });
      if (res.ok) return res.json();
    } catch {
      /* retry */
    }
    await sleep(1000 * (attempt + 1));
  }
  throw new Error(`API failed: ${url.slice(0, 120)}`);
}

async function main() {
  const { titles } = JSON.parse(await readFile(path.join(ROOT, 'shared/item-wiki.json'), 'utf8'));
  // item-wiki.json values: { title, id? } (older files: plain title string)
  const meta = Object.fromEntries(Object.entries(titles).map(([n, v]) => [n, typeof v === 'string' ? { title: v } : v]));
  const entries = Object.entries(meta).map(([n, v]) => [n, v.title]); // [name, title]
  // D-82: drops on the creature sheets that are not in the sale catalog (quest items, trash, "Book (Orange)"…)
  const known = new Set(entries.map(([n]) => slug(n)));
  const { creatures } = JSON.parse(await readFile(path.join(ROOT, 'shared/creature-wiki.json'), 'utf8'));
  for (const name of new Set(Object.values(creatures).flatMap((c) => c.loot.map((l) => l.i)))) {
    if (known.has(slug(name))) continue;
    known.add(slug(name));
    meta[name] = { title: name };
    entries.push([name, name]);
  }
  await mkdir(OUT, { recursive: true });

  // 1) Resolve image URLs, 50 files per request
  const urls = new Map(); // name → url
  for (let i = 0; i < entries.length; i += 50) {
    const chunk = entries.slice(i, i + 50);
    const fileOf = new Map(chunk.map(([name, title]) => [`File:${title}.gif`, name]));
    const d = await api({ action: 'query', prop: 'imageinfo', iiprop: 'url', titles: [...fileOf.keys()].join('|') });
    const norm = new Map((d.query.normalized ?? []).map((n) => [n.to, n.from]));
    for (const p of d.query.pages ?? []) {
      const url = p.imageinfo?.[0]?.url;
      const name = fileOf.get(norm.get(p.title) ?? p.title);
      if (url && name) urls.set(name, url);
    }
    process.stderr.write(`\rresolve: ${Math.min(i + 50, entries.length)}/${entries.length}`);
    await sleep(200);
  }
  process.stderr.write('\n');

  // 2) Index: slug → path below the CDN base (e.g. "1/13/Dragon_Shield.gif")
  const sprites = {};
  for (const [name] of entries.sort(([a], [b]) => a.localeCompare(b))) {
    const url = urls.get(name);
    const clean = url?.split('/revision/')[0];
    const wikiPath = clean?.startsWith(CDN) ? clean.slice(CDN.length) : '';
    const id = meta[name].id ?? 0;
    if (id || wikiPath) sprites[slug(name)] = [id, wikiPath];
  }
  // D-82: the address the wiki gives wins over the fixed one
  for (const [coin, wikiPath] of Object.entries(COINS)) sprites[coin] ??= [0, wikiPath];
  await writeFile(
    path.join(OUT, 'items.json'),
    JSON.stringify({
      _comment: `Generated by scripts/import-sprites.mjs on ${new Date().toISOString().slice(0, 10)}. Item images © CipSoft GmbH, hosted by TibiaWiki.`,
      official: 'https://static.tibia.com/images/charactertrade/objects/',
      wiki: CDN,
      sprites,
    }) + '\n',
  );
  console.error(`indexed ${Object.keys(sprites).length}/${entries.length} item images`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
