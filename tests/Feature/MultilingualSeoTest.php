<?php

namespace Tests\Feature;

use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class MultilingualSeoTest extends TestCase
{
    use RefreshDatabase;

    public function test_home_renders_in_portuguese_by_default(): void
    {
        $response = $this->get('/');

        $response->assertOk();
        $response->assertSee('Solicitar consulta');
    }

    public function test_home_en_renders_in_english_regardless_of_session(): void
    {
        // Even with a pt-BR session locale lingering from a previous visit,
        // the /en URL must deterministically render in English - that's
        // the whole point of giving crawlers a stable per-language URL.
        $this->withSession(['locale' => 'pt-BR']);

        $response = $this->get('/en');

        $response->assertOk();
        $response->assertSee('Request a reading');
        $response->assertDontSee('Solicitar consulta');
    }

    public function test_home_es_renders_in_spanish(): void
    {
        $response = $this->get('/es');

        $response->assertOk();
        $response->assertSee('Cómo podemos ayudarte');
    }

    public function test_privacy_en_renders_in_english(): void
    {
        $response = $this->get('/en/privacy-policy');

        $response->assertOk();
        $response->assertSee('Privacy Policy');
    }

    public function test_home_page_includes_hreflang_alternates(): void
    {
        $response = $this->get('/');

        $response->assertOk();
        $response->assertSee('hreflang="en"', false);
        $response->assertSee('hreflang="es"', false);
        $response->assertSee('hreflang="x-default"', false);
    }

    public function test_sitemap_route_lists_localized_urls(): void
    {
        // sitemap.xml used to be a static file served directly by the
        // webserver; it's now generated by SitemapController so it can
        // include published blog articles too.
        $response = $this->get(route('sitemap'));

        $response->assertOk();
        $response->assertHeader('Content-Type', 'application/xml');
        $response->assertSee(url('/en'), false);
        $response->assertSee(url('/es'), false);
        $response->assertSee('hreflang="x-default"', false);
    }
}
