        function acceptLgpdCookies() {
            localStorage.setItem('lgpd_consent_accepted', 'true');
            const banner = document.getElementById('lgpd-cookie-banner');
            banner.classList.add('translate-y-12', 'opacity-0');
            setTimeout(() => {
